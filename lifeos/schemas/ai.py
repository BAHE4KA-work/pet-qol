"""AI triage, extraction, weekly planning, and analytics schemas."""

from __future__ import annotations

from datetime import date, datetime
from typing import Literal

from pydantic import BaseModel, Field

ItemType = Literal["event", "task", "goal_idea", "noise"]
EnergyTier = Literal["deep", "medium", "low"]
ConfidenceTier = Literal["high", "medium", "low"]
DayAnchor = Literal["morning", "afternoon", "evening"]


class TriageResult(BaseModel):
    """Calibrated output from Tier 1 (gemini-decision-1) single-pass evaluation."""

    is_actionable: float = Field(ge=0.0, le=1.0)
    confidence: float = Field(ge=0.0, le=1.0)
    item_type: ItemType
    energy_tier: EnergyTier
    needs_hydrogen: float = Field(ge=0.0, le=1.0)
    urgency: int = Field(ge=1, le=5)
    cognitive_load: int = Field(ge=1, le=5)
    should_discard: bool = False


class SubtaskSpec(BaseModel):
    """Actionable micro-step or subtask produced by Tier 2 / Tier 3."""

    title: str = Field(min_length=1, max_length=240)
    dod: str = Field(min_length=1, max_length=500, description="Definition of Done")
    duration_bucket: int = Field(default=1, ge=1, le=5)
    cognitive_load: int = Field(default=2, ge=1, le=5)
    energy_tier: EnergyTier = "low"


class ExtractedItem(BaseModel):
    """Normalized actionable item extracted by Tier 2 or Tier 3."""

    title: str = Field(min_length=1, max_length=240)
    dod: str = Field(min_length=1, max_length=500, description="Definition of Done")
    item_type: ItemType = "task"
    energy_tier: EnergyTier = "medium"
    duration_bucket: int = Field(default=2, ge=1, le=5)
    cognitive_load: int = Field(default=3, ge=1, le=5)
    urgency: int = Field(default=3, ge=1, le=5)
    suggested_anchor: DayAnchor | None = None
    due_at: datetime | None = None
    has_exact_time: bool = False
    linked_goal_id: str | None = None
    linked_project_id: str | None = None
    duplicate_of_task_id: str | None = None
    has_schedule_conflict: bool = False
    subtasks: list[SubtaskSpec] = Field(default_factory=list)


class WeeklyPlanSlot(BaseModel):
    """Single scheduled task assignment for weekly planning."""

    task_id: str
    scheduled_date: date
    day_anchor: DayAnchor
    rationale: str = ""


class WeeklyPlanOutput(BaseModel):
    """Holistic weekly schedule generated by Tier 3 (gemini-4-hydrogen)."""

    week_start: date
    slots: list[WeeklyPlanSlot] = Field(default_factory=list)
    focus_theme: str = ""
    overload_warning: str | None = None


class WeeklyAnalyticsOutput(BaseModel):
    """Passive weekly analytics summary generated by Tier 3 for Notion/psychologist."""

    week_start: date
    summary_markdown: str
    sleep_productivity_corr: float | None = None
    procrastination_patterns: list[str] = Field(default_factory=list)
    goal_progress_notes: dict[str, str] = Field(default_factory=dict)
    recommendations: list[str] = Field(default_factory=list)
